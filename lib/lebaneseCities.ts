export function searchLebaneseCitiesFull(query: string): LebaneseCityEntry[] {
  if (!query || !query.trim()) {
    return LEBANESE_CITIES_FULL;
  }
  const q = query.toLowerCase().trim();
  return LEBANESE_CITIES_FULL.filter((city) => {
    return (
      city.name.toLowerCase().includes(q) ||
      city.district.toLowerCase().includes(q)
    );
  });
}


