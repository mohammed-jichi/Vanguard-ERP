export interface LanguageProviderProps {
  children: React.ReactNode;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<LanguageProviderProps> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageCode>('en');
  const [dir, setDir] = useState<'ltr' | 'rtl'>('ltr');

  // Initialize language from localStorage on client mount
  useEffect(() => {
    if (typeof window !== 'undefined') {
      try {
        const saved = localStorage.getItem('vanguard_language') as LanguageCode;
        if (saved && ALL_LANGUAGES.some(l => l.code === saved)) {
          setLanguageState(saved);
          const newDir = isRTL(saved) ? 'rtl' : 'ltr';
          setDir(newDir);
          document.documentElement.dir = newDir;
          document.documentElement.lang = saved;
        }
      } catch (e) {
        console.warn('Failed to load language preference:', e);
      }
    }
  }, []);

  const setLanguage = (lang: LanguageCode) => {
    setLanguageState(lang);
    const newDir = isRTL(lang) ? 'rtl' : 'ltr';
    setDir(newDir);

    if (typeof window !== 'undefined') {
      try {
        localStorage.setItem('vanguard_language', lang);
      } catch (e) {
        console.warn('Failed to persist language preference:', e);
      }
      document.documentElement.dir = newDir;
      document.documentElement.lang = lang;
    }
  };

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.dir = dir;
      document.documentElement.lang = language;
    }
  }, [dir, language]);

  const t = (key: string, fallbackEn?: string): string => {
    // 1. Current selected language
    const langMap = translations[language];
    if (langMap && langMap[key]) {
      return langMap[key];
    }
    // 2. If RTL language (e.g. fa, ur, he) and key is missing, check Arabic next
    if (isRTL(language) && translations['ar']?.[key]) {
      return translations['ar'][key];
    }
    // 3. Fallback to English dictionary
    if (translations['en']?.[key]) {
      return translations['en'][key];
    }
    // 4. Fallback to Arabic dictionary if English is missing
    if (translations['ar']?.[key]) {
      return translations['ar'][key];
    }
    // 5. Fallback to provided fallbackEn or key
    return fallbackEn || key;
  };

  const contextValue: LanguageContextType = {
    language,
    dir,
    direction: dir,
    isRtl: dir === 'rtl',
    setLanguage,
    t,
    languages: ALL_LANGUAGES,
    pinnedLanguages: PINNED_LANGUAGES,
    extendedLanguages: EXTENDED_LANGUAGES,
  };

  return (
    <LanguageContext.Provider value={contextValue}>
      <div dir={dir} className="w-full min-h-screen">
        {children}
      </div>
    </LanguageContext.Provider>
  );
};

export const useLanguage = (): LanguageContextType => {
  const context = useContext(LanguageContext);
  if (!context) {
    return {
      language: 'en',
      dir: 'ltr',
      direction: 'ltr',
      isRtl: false,
      setLanguage: () => {},
      t: (key: string, fallbackEn?: string) => fallbackEn || key,
      languages: ALL_LANGUAGES,
      pinnedLanguages: PINNED_LANGUAGES,
      extendedLanguages: EXTENDED_LANGUAGES,
    };
  }
  return context;
};
